#!/usr/bin/env python3
"""Generates regex.m from regex_tpl.m: each case's expected matches come from Python's re (the reference).
Usage: python3 tests/objc/regex_gen.py   (run again after editing the cases)"""
import os, re
cases = [
 (r"([A-Za-z_][A-Za-z0-9_]{0,127})=c([0-7]);", "pos=c0;normal=c1;uv_2=c7;"),
 (r"a*", "baaac"), (r"a+?", "aaa"), (r"(a|ab)(c|bcd)(d*)", "abcd"), (r"\d+", "x12y345z"),
 (r"(\w+)@(\w+)\.com", "ana@example.com and luis@mail.com"), (r"^\s*#", "  # comment"),
 (r"(?i)hello", "HeLLo hello HELLO"), (r"\bcat\b", "cat concat cat."), (r"colou?r", "color colour colouur"),
 (r"(\d{2})-(\d{2})-(\d{4})", "date 23-10-2026 and 01-01-1999"), (r"[^aeiou\s]+", "the bat is an animal"),
 (r"(?<=\$)\d+", "costs $42 or $7"), (r"(?<!\$)\b\d+", "costs $42 or 7"), (r"\d+(?=€)", "10€ 20$ 30€"),
 (r"(?!un)\b\w+", "un two uno three"), (r"(a)(?:b)(c)?", "ab abc"), (r"(\w)\1", "hello aabb"),
 (r"(?P<y>\d{4})-(?P<m>\d\d)", "2026-10"), (r"x{2,3}", "xxxxxxx"), (r"x{2,}?", "xxxxx"),
 (r".+", "línea1\nlínea2"), (r"(?s).+", "a\nb"), (r"(?m)^\w+$", "one\ntwo\nthree"),
 (r"[a-c-]+", "a-b-c-d"), (r"[\d.]+", "v1.2.3 and 4"), (r"\W+", "hola, ¿qué tal?"), (r"(a*)*b", "aaab"),
 (r"(a*)+$", "aaa"), (r"(?:ab)*c", "ababc abc c"), (r"ñ+", "ñññandú"), (r"[à-ÿ]+", "canción núm"),
 (r"(\d+)\s*(?:px|em)", "10px 2 em 3pt"), (r"\s+$", "text   "), (r"^$", ""), (r"", "ab"),
 (r"a|b|c", "xbyaz"), (r"(?i)[a-z]+", "ÑAndú ABC"), (r"\.\*", "a.*b"), (r"[\[\]]", "[x]"),
 (r"(?x) \d+ \s* \# note", "12 # note"), (r"(?:(?:a)+)+b", "aaaaab"), (r"\\", "a\\b"),
]
def lit(s):  # Objective-C string literal (all test strings are in the BMP, so Python indices are UTF-16 indices)
    return '@"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'
rows = []
for p, s in cases:
    ms = list(re.finditer(p, s)); ng = (len(ms[0].groups()) + 1) if ms else 1
    r = [x for m in ms for i in range(ng) for x in ((m.start(i), m.end(i)) if m.start(i) >= 0 else (-1, -1))]
    rows.append('    { %s, %s, %d, %d, (long[]){%s} },' % (lit(p.replace("(?P<", "(?<")), lit(s), len(ms), ng, ', '.join(map(str, r)) or '0'))
d = os.path.dirname(os.path.abspath(__file__))
tpl = open(os.path.join(d, 'regex_tpl.m'), encoding='utf-8').read()
open(os.path.join(d, 'regex.m'), 'w', encoding='utf-8').write(tpl.replace('/*CASES*/', '/* generated by regex_gen.py */\n' + '\n'.join(rows)))
print(len(rows), 'cases')
